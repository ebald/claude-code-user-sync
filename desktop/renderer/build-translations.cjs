'use strict';
const fs = require('node:fs');
const path = require('node:path');
const resources = Object.fromEntries(['en', 'es', 'pt-BR'].map((language) => [language, {
  translation: JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'locales', `${language}.json`), 'utf8')),
}]));
const json = JSON.stringify(resources, null, 2).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
fs.writeFileSync(path.join(__dirname, 'translations.js'), `/* Generated by build-translations.cjs from desktop/locales. */\nwindow.SYNC_TRANSLATIONS = ${json};\n`);
